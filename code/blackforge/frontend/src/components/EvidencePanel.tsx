import { useState } from 'react'
import type { Finding, PatchAttempt, PatchResult, RefereeResult } from '../types'

type Tab = 'reproduction' | 'test' | 'log' | 'stack' | 'diff'

interface EvidencePanelProps {
  finding: Finding | null
  referee: RefereeResult | null
  patch: PatchAttempt | null
  patchResult: PatchResult | null
  activityDiscoveryModel: string | null
  visible: boolean
}

export function EvidencePanel({
  finding,
  referee,
  patch,
  patchResult,
  activityDiscoveryModel,
  visible,
}: EvidencePanelProps) {
  const [tab, setTab] = useState<Tab>('test')
  const beforeFailed = Boolean(visible && referee?.reproduced)
  const afterPassed = Boolean(visible && patchResult?.attack_test_passed)

  return (
    <section className="surface">
      <div className="surface-header">
        <div className="flex min-w-0 flex-wrap items-center gap-2">
          <h2 className="section-label">Evidence</h2>
          {beforeFailed && (
            <span className="badge badge-danger">Before patch · FAILED</span>
          )}
          {afterPassed && (
            <span className="badge badge-success">After patch · PASSED</span>
          )}
        </div>
      </div>

      {!visible || !finding ? (
        <div className="empty">Evidence appears after reproduction.</div>
      ) : (
        <div className="fade-in">
          <div className="tabs">
            {(
              [
                ['reproduction', 'Reproduction'],
                ['test', 'Generated test'],
                ['log', 'Execution log'],
                ['stack', 'Stack trace'],
                ['diff', 'Patch diff'],
              ] as const
            ).map(([id, label]) => (
              <button
                key={id}
                type="button"
                className={`tab ${tab === id ? 'tab-active' : ''}`}
                onClick={() => setTab(id)}
              >
                {label}
              </button>
            ))}
          </div>

          <div className="p-3">
            {tab === 'reproduction' && (
              <ol className="list-decimal space-y-1 pl-4 text-[12px] text-[var(--text-secondary)]">
                {finding.reproduction_steps.map((step) => (
                  <li key={step}>{step}</li>
                ))}
              </ol>
            )}

            {tab === 'test' && (
              <div className="space-y-2">
                <div className="flex flex-wrap gap-x-4 gap-y-1 text-[11px] text-[var(--text-muted)]">
                  <span>
                    File{' '}
                    <span className="mono text-[var(--text-secondary)]">
                      {finding.test_path}
                    </span>
                  </span>
                  <span>
                    Generated by{' '}
                    <span className="text-[var(--text-secondary)]">
                      {activityDiscoveryModel ?? 'Discovery model'}
                    </span>
                  </span>
                  <span>
                    Verified by{' '}
                    <span className="text-[var(--text-secondary)]">
                      Execution sandbox
                    </span>
                  </span>
                  <span>
                    Status{' '}
                    <span className="text-[var(--text-secondary)]">
                      {referee?.reproduced ? 'Reproduced' : 'Pending'}
                    </span>
                  </span>
                </div>
                <div className="code-block">
                  <div className="border-b border-[var(--border-muted)] px-3 py-1.5 mono text-[11px] text-[var(--text-muted)]">
                    {finding.test_name}
                  </div>
                  <pre>
                    <code>{finding.generated_test}</code>
                  </pre>
                </div>
              </div>
            )}

            {tab === 'log' && (
              <div className="code-block">
                <pre>
                  {referee?.execution_output ??
                    'Waiting for isolated execution output…'}
                </pre>
              </div>
            )}

            {tab === 'stack' && (
              <div className="code-block">
                <pre>
                  {finding.stack_trace ||
                    referee?.execution_output ||
                    'No stack trace captured.'}
                </pre>
              </div>
            )}

            {tab === 'diff' && (
              <div className="code-block">
                <pre>
                  {patch?.patch ?? 'Patch diff appears after patch generation.'}
                </pre>
              </div>
            )}
          </div>
        </div>
      )}
    </section>
  )
}
